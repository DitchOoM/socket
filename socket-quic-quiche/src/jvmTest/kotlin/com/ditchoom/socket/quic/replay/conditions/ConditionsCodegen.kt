package com.ditchoom.socket.quic.replay.conditions

import com.ditchoom.socket.quic.core.life.ConnEnd
import kotlin.reflect.KClass
import kotlin.time.Duration
import kotlin.time.Duration.Companion.seconds

/**
 * Writes [Conditions] as a Kotlin fixture and a test that replays it. The fixture holds only what was derived (windows,
 * OS events, ordinals and documentation addresses), never a datagram or a real address, so it can be committed.
 */
internal object ConditionsCodegen {
    const val PACKAGE = "com.ditchoom.socket.quic.replay.conditions"

    fun fixture(
        conditions: Conditions,
        valName: String,
    ): String =
        buildString {
            appendLine("// GENERATED by conditionsFromTrace from ${conditions.source} — regenerate, do not edit.")
            appendLine("// Derived conditions only: link windows, OS events, network ordinals, documentation addresses.")
            appendLine("@file:Suppress(\"ktlint\")")
            appendLine()
            appendLine("package $PACKAGE.fixtures")
            appendLine()
            for (name in IMPORTS) appendLine("import $PACKAGE.$name")
            appendLine("import kotlin.time.Duration.Companion.nanoseconds")
            appendLine()
            appendLine("internal val $valName: Conditions =")
            appendLine("    Conditions(")
            appendLine("        name = \"${conditions.name}\",")
            appendLine("        source = \"${conditions.source}\",")
            appendLine("        family = Family.${conditions.family},")
            appendLine("        evidence = Evidence.${conditions.evidence},")
            appendLine("        start = ${up(conditions.start)},")
            appendLine("        echoEvery = ${ns(conditions.echoEvery)},")
            appendLine("        idleTimeout = ${ns(conditions.idleTimeout)},")
            appendLine("        link = listOf(")
            for (window in conditions.link) appendLine("            ${window(window)},")
            appendLine("        ),")
            appendLine("        os = listOf(")
            for (event in conditions.os) appendLine("            ${event(event)},")
            appendLine("        ),")
            appendLine("        runFor = ${ns(conditions.runFor)},")
            appendLine("    )")
        }

    /** A test that replays [valName] twice and holds it to [expect]: what the replay gave when the fixture was made. */
    fun test(
        className: String,
        valName: String,
        expect: Expect,
    ): String =
        buildString {
            appendLine("package $PACKAGE")
            appendLine()
            if (expect is Expect.Ends) appendLine("import com.ditchoom.socket.quic.core.life.ConnEnd")
            appendLine("import $PACKAGE.fixtures.$valName")
            appendLine("import kotlin.test.Test")
            appendLine("import kotlin.time.Duration.Companion.nanoseconds")
            appendLine()
            appendLine("/** The walk recording behind [$valName], replayed as conditions: the outcome it had when the fixture was made. */")
            appendLine("class $className {")
            appendLine("    @Test")
            appendLine("    fun replaysToTheSameOutcomeTwice() {")
            appendLine("        replayTwice($valName, ${expectation(expect)})")
            appendLine("    }")
            appendLine("}")
        }

    /** What a test expects of an outcome that was observed: the same end, or survival within the round trips seen. */
    fun expectOf(
        outcome: Outcome,
        conditions: Conditions,
    ): Expect =
        when (outcome) {
            is Outcome.Ended -> Expect.Ends(outcome.end, (outcome.at.inWholeSeconds + 1).seconds)
            is Outcome.Survived -> Expect.Survives(conditions.roundTrip() * 2)
        }

    private fun expectation(expect: Expect): String =
        when (expect) {
            is Expect.Survives -> "Expect.Survives(firstEchoWithin = ${ns(expect.firstEchoWithin)})"
            is Expect.Ends -> "Expect.Ends(${endName(expect.end)}::class, notAfter = ${ns(expect.notAfter)})"
        }

    private fun endName(end: KClass<out ConnEnd>): String = "ConnEnd.${end.simpleName}"

    private fun up(up: NetUp): String = "NetUp(NetHandle(NetKind.${up.network.kind}, ${up.network.ordinal}), Validation.${up.validation})"

    private fun window(window: LinkWindow): String =
        when (window) {
            is LinkWindow.Outage -> "LinkWindow.Outage(${ns(window.from)}, ${ns(window.until)})"
            is LinkWindow.Flowing ->
                "LinkWindow.Flowing(${ns(window.from)}, ${ns(window.until)}, DelayRange(${ns(window.delay.min)}, " +
                    "${ns(window.delay.max)}), PerMille(${window.lossToPeer.value}), PerMille(${window.lossFromPeer.value}))"
        }

    private fun event(event: OsEvent): String =
        when (event) {
            is OsEvent.Offline -> "OsEvent.Offline(${ns(event.at)})"
            is OsEvent.Up -> "OsEvent.Up(${ns(event.at)}, ${up(event.up)})"
            is OsEvent.Route ->
                "OsEvent.Route(${ns(event.at)}, " +
                    when (val route = event.route) {
                        RouteFrom.Bound -> "RouteFrom.Bound)"
                        RouteFrom.NoRoute -> "RouteFrom.NoRoute)"
                        is RouteFrom.Other -> "RouteFrom.Other(\"${route.address}\"))"
                    }
        }

    private fun ns(duration: Duration): String = "${duration.inWholeNanoseconds}L.nanoseconds"

    private val IMPORTS =
        listOf(
            "Conditions",
            "DelayRange",
            "Evidence",
            "Family",
            "LinkWindow",
            "NetHandle",
            "NetKind",
            "NetUp",
            "OsEvent",
            "PerMille",
            "RouteFrom",
            "Validation",
        )
}

/** The longest round trip any flowing window allows. */
internal fun Conditions.roundTrip(): Duration = link.filterIsInstance<LinkWindow.Flowing>().maxOf { it.delay.max } * 2
